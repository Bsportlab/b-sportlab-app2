function applyPhraseList(text, rules) {
  let out = String(text || '');
  for (const [rx, replacement] of rules) {
    out = out.replace(rx, replacement);
  }
  return out;
}

export function trFood(name, lang = 'it') {
  const clean = String(name || '').trim();
  if (!clean || lang === 'it') return clean;

  const norm = normalizeSearchText(clean);
  if (FOOD_DICT[clean]?.[lang]) return FOOD_DICT[clean][lang];
  if (FOOD_DICT[norm]?.[lang]) return FOOD_DICT[norm][lang];

  let out = clean;
  for (const [itNorm, val] of NORMALIZED_FOOD_ENTRIES) {
    const target = val[lang];
    if (!target || itNorm.length < 2) continue;
    const escaped = itNorm.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const rx = new RegExp(`(^|[^a-zà-öø-ÿ0-9’])${escaped}(?=[^a-zà-öø-ÿ0-9’]|$)`, 'gi');
    if (rx.test(normalizeSearchText(out))) {
      out = out.replace(rx, (match, prefix) => `${prefix}${target}`);
    }
  }

  out = applyPhraseList(out, lang === 'en' ? PREP_PHRASES_EN : PREP_PHRASES_FR);
  return out.replace(/\s+/g, ' ').trim();
}

export function trRecipeText(recipe, lang = 'it') {
  if (!recipe) return { title: '', steps: '' };
  if (lang === 'it') return { title: recipe.n || '', steps: recipe.st || '' };

  const custom = recipe.tr?.[lang];
  if (custom && (custom.title || custom.steps)) {
    return {
      title: custom.title || recipe.n || '',
      steps: custom.steps || recipe.st || '',
    };
  }

  let title = String(recipe.n || '');
  let steps = String(recipe.st || '');

  const phraseRules = lang === 'en' ? RECIPE_PHRASES_EN : RECIPE_PHRASES_FR;
  title = applyPhraseList(title, phraseRules);
  steps = applyPhraseList(steps, phraseRules);

  for (const [itKey, val] of NORMALIZED_FOOD_ENTRIES) {
    const target = val[lang];
    if (!target || itKey.length < 3) continue;
    const escaped = itKey.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const rx = new RegExp(`(^|[^a-zà-öø-ÿ0-9’])${escaped}(?=[^a-zà-öø-ÿ0-9’]|$)`, 'gi');
    title = title.replace(rx, (m, p) => `${p}${target}`);
    steps = steps.replace(rx, (m, p) => `${p}${target}`);
  }

  return {
    title: title.replace(/\s+/g, ' ').trim(),
    steps: steps.replace(/\s+/g, ' ').trim(),
  };
}