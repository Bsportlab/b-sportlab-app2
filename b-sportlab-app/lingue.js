export const normalizeSearchText = (str = '') =>
  String(str || '')
    .toLowerCase()
    .replace(/['’`]/g, '’')
    .replace(/\s+/g, ' ')
    .trim();

export function expandFoodTerms(rawInput = '') {
  const tokens = normalizeSearchText(rawInput)
    .split(/[,;.\n/]+/)
    .map((x) => normalizeSearchText(x))
    .filter(Boolean);

  const expanded = new Set();

  tokens.forEach((term) => {
    expanded.add(term);

    Object.entries(FOOD_CATEGORIES).forEach(([catName, items]) => {
      const normCat = normalizeSearchText(catName);
      const normItems = items.map(normalizeSearchText);
      if (term === normCat || normItems.includes(term)) {
        expanded.add(normCat);
        normItems.forEach((it) => expanded.add(it));
      }
    });

    SYNONYM_GROUPS.forEach((group) => {
      const normGroup = group.map(normalizeSearchText);
      if (normGroup.some((g) => g === term || g.includes(term) || term.includes(g))) {
        normGroup.forEach((g) => expanded.add(g));
      }
    });
  });

  return Array.from(expanded);
}

