// Helper per ottenere un alimento dato il suo id
export function getAlimentoById(id) {
  if (!id) return null;
  return ALIMENTI_DB.find((item) => item.id === id) || null;
}

// Helper per ottenere tutti gli alimenti di una categoria ('C', 'P', 'F', 'V', 'FR')
export function getAlimentiByCat(cat) {
  if (!cat) return [];
  return ALIMENTI_DB.filter((item) => item.cat === cat);
}

// Funzione di ricerca istantanea nel database alimenti per Diario Libero
export function searchAlimenti(query = '', filters = {}) {
  const q = String(query || '').toLowerCase().trim();
  if (!q) return [];
  const tokens = q.split(/\s+/).filter(Boolean);

  return ALIMENTI_DB.filter((item) => {
    // Esclusione filtri intolleranze/preferenze del paziente
    if (filters.glutenFree && item.tags.includes('glutine')) return false;
    if (filters.dairyFree && (item.tags.includes('dairy') || item.tags.includes('latticini'))) return false;
    if (filters.vegetarian && (item.tags.includes('carne') || item.tags.includes('pesce') || item.tags.includes('molluschi') || item.tags.includes('crostacei'))) return false;

    // Ricerca testuale su nome, categoria e tag
    const hay = `${item.nome} ${item.servingUnit || ''} ${item.tags.join(' ')}`.toLowerCase();
    return tokens.every((tok) => hay.includes(tok));
  });
}
